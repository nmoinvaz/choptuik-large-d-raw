#!/usr/bin/env python3
"""Writes INDEX.md: one row per task folder, from the first line of the folder's README.md ("# <folder>: <what it
holds>"), the machine (the folder's -win / -mac suffix, else its README's "Machine:" line) and, for the folders
imported from the code repository's raw/<name> branches, that branch and its last commit (from the import commit's
message). The rows change only when a folder is added or its title changes, so two machines rarely edit it at once.

    python3 make_index.py [--check] [--stats]

--check: write nothing; exit 1 if INDEX.md differs from what this script writes, or a folder's README.md is missing
or does not start with "# <folder>: ". --stats: print each folder's files, MB and first and last commit (not part of
INDEX.md, which would then change on every push).
"""
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))


def git(*a):
    return subprocess.run(["git", "-C", ROOT, *a], capture_output=True, text=True).stdout


def folders():
    key = lambda n: [int(t) if t.isdigit() else t for t in re.split(r"(\d+)", n)]  # noqa: E731
    return sorted((n for n in os.listdir(ROOT) if os.path.isdir(os.path.join(ROOT, n)) and not n.startswith(".")),
                  key=key)


def title(name):
    """the description from README.md's first line, or None if it is missing or not of the form '# <name>: ...'"""
    p = os.path.join(ROOT, name, "README.md")
    if not os.path.exists(p):
        return None
    first = open(p, encoding="utf-8").readline().strip()
    pre = f"# {name}: "
    return first[len(pre):].strip() if first.startswith(pre) else None


def machine(name):
    m = re.search(r"-(win|mac|cloud)$", name)
    if m:
        return m.group(1)
    txt = open(os.path.join(ROOT, name, "README.md"), encoding="utf-8").read()
    m = re.search(r"^Machine: *(\S+)", txt, re.M)
    return m.group(1).rstrip(".,") if m else ""


def source(name):
    m = re.search(r"^Import raw/(\S+) \((\w+)\)", git("log", "--format=%s", "--", name), re.M)
    return f"raw/{m.group(1)} {m.group(2)}" if m else ""


def index():
    rows, bad = [], []
    for n in folders():
        t = title(n)
        if t is None:
            bad.append(n)
            continue
        rows.append(f"| [{n}]({n}/) | {t} | {machine(n)} | {source(n)} |")
    head = ["# Index", "",
            "Generated by `make_index.py` from each folder's README.md; do not edit by hand. \"Imported from\" is the "
            "code repository's branch and its last commit, which this repository keeps.", "",
            "| folder | what it holds | machine | imported from |", "|---|---|---|---|"]
    return "\n".join(head + rows) + "\n", bad


def stats():
    for n in folders():
        files = [os.path.join(d, f) for d, _, fs in os.walk(os.path.join(ROOT, n)) for f in fs]
        mb = sum(os.path.getsize(f) for f in files) / 1e6
        dates = git("log", "--format=%cs", "--", n).split()
        print(f"{n:16s} {len(files):5d} files {mb:8.2f} MB  {dates[-1] if dates else '-'} .. {dates[0] if dates else '-'}")


def main():
    if "--stats" in sys.argv:
        stats()
        return
    txt, bad = index()
    for n in bad:
        print(f"{n}/README.md: missing, or its first line is not '# {n}: <what it holds>'")
    path = os.path.join(ROOT, "INDEX.md")
    if "--check" in sys.argv:
        stale = not os.path.exists(path) or open(path, encoding="utf-8").read() != txt
        if stale:
            print("INDEX.md is stale: run python3 make_index.py")
        sys.exit(1 if stale or bad else 0)
    open(path, "w", encoding="utf-8").write(txt)
    print(f"INDEX.md: {txt.count(chr(10)) - 6} folders" + (f", {len(bad)} without a title line" if bad else ""))
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
